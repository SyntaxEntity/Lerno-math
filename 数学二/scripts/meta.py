def get(subject_key):
    return TOPICS[subject_key]


def all_topics():
    """按 ORDER 顺序遍历 (subject_key, topic)。"""
    for k in ORDER:
        for t in TOPICS[k]:
            yield k, t


def freq_line(subject_key, topic_name):
    """返回某知识点的标准考频统计行（生成脚本与校验脚本共用，保证逐字一致）。"""
    for t in TOPICS[subject_key]:
        if t[0] == topic_name:
            _, times, years, pts, qtype, hot, slug = t
            times_txt = PENDING if times == PENDING else "%d 次" % times
            if times == PENDING:
                years_txt = years
            else:
                years_txt = "%s（%s）" % (years, SAMPLE_NOTE)
            return ("**考频统计**：考察次数 %s；涉及年份：%s；分数占比约 %s；"
                    "主要题型：%s。" % (times_txt, years_txt, ratio_of(subject_key, slug), qtype))
    raise KeyError((subject_key, topic_name))


def ratio_of(subject_key, slug):
    """该章占本科目分值的百分比（由分值现算，不手写，避免不自洽）。"""
    sub = SUBJECTS[subject_key]
    for t in TOPICS[subject_key]:
        if t[6] == slug:
            return "%.0f%%" % (100.0 * t[3] / sub["score"])
    raise KeyError((subject_key, slug))


def points_of(subject_key, slug):
    for t in TOPICS[subject_key]:
        if t[6] == slug:
            return t[3]
    raise KeyError((subject_key, slug))


def subject_points(subject_key):
    return sum(t[3] for t in TOPICS[subject_key])


def check():
    """自检：分值合计、slug 唯一、科目结构自洽。失败即抛异常，不让错误数据流出去。"""
    total = sum(SUBJECTS[k]["score"] for k in ORDER)
    assert total == EXAM["total"], "科目分值合计 %d ≠ %d" % (total, EXAM["total"])
    assert total == 117 + 33, "高数 117 + 线代 33 的口径被改动，请同步 README"
    slugs = []
    for k in ORDER:
        s = subject_points(k)
        assert s == SUBJECTS[k]["score"], \
            "%s 各章分值合计 %d ≠ 科目分值 %d" % (SUBJECTS[k]["name"], s, SUBJECTS[k]["score"])
        assert len(TOPICS[k]) == SUBJECTS[k]["chapters"], \
            "%s 章节数 %d ≠ 声明 %d" % (SUBJECTS[k]["name"], len(TOPICS[k]), SUBJECTS[k]["chapters"])
        for t in TOPICS[k]:
            assert len(t) == 7, "topic 元组必须 7 个字段：%r" % (t,)
            slugs.append(t[6])
    assert len(slugs) == len(set(slugs)), "slug 重复：%s" % slugs
    assert len(slugs) == 15, "知识点总数应为 15（高数 9 + 线代 6），实为 %d" % len(slugs)
    # 次数必须为非负整数或 PENDING
    for k, t in all_topics():
        if t[1] != PENDING:
            assert isinstance(t[1], int) and t[1] >= 0, "次数非法：%r" % (t,)
    return True


